const dictionaries: Record<Locale, Messages> = { ja, en, zh };

export function localeFromLanguage(language: string | undefined, setting: LocaleSetting): Locale {
  if (setting === "ja" || setting === "en" || setting === "zh") return setting;
  const normalized = (language ?? "").toLowerCase();
  if (normalized.startsWith("zh")) return "zh";
  if (normalized.startsWith("en")) return "en";
  return "ja";
}

export class I18n {
  private messages: Messages;

  constructor(locale: Locale) {
    this.messages = dictionaries[locale];
  }

  setLocale(locale: Locale): void {
    this.messages = dictionaries[locale];
  }

  t(key: string, values?: Record<string, string | number>): string {
    const template = this.messages[key] ?? dictionaries.en[key] ?? key;
    if (!values) return template;
    return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
    );
  }

  has(key: string): boolean {
    return key in this.messages;
  }
}

export function messageKeys(): string[] {
  return Object.keys(ja).sort();
}

export function missingKeys(locale: Locale): string[] {
  const reference = messageKeys();
  const target = new Set(Object.keys(dictionaries[locale]));
  const english = new Set(Object.keys(en));
  return reference.filter((key) => !target.has(key) || !english.has(key));
}
