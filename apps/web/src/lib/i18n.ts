const stored = typeof window !== "undefined" ? window.localStorage.getItem("hpa.locale") : null;
const initial = stored && (locales as readonly string[]).includes(stored) ? stored : "ja";

void i18n.use(initReactI18next).init({
  resources: {
    ja: { translation: ja },
    en: { translation: en },
    zh: { translation: zh },
  },
  lng: initial,
  fallbackLng: "en",
  supportedLngs: locales,
  interpolation: { escapeValue: false },
  returnNull: false,
});

if (typeof document !== "undefined") {
  document.documentElement.lang = initial;
}

export function setLocale(locale: Locale) {
  void i18n.changeLanguage(locale);
  window.localStorage.setItem("hpa.locale", locale);
  document.documentElement.lang = locale;
}

export function currentLocale(): Locale {
  const language = i18n.resolvedLanguage ?? i18n.language;
  return language.startsWith("zh") ? "zh" : language.startsWith("en") ? "en" : "ja";
}

export function formatDate(value: string | undefined, locale = currentLocale()): string {
  if (!value) {
    return "—";
  }
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return value;
  }
  return new Intl.DateTimeFormat(locale === "ja" ? "ja-JP" : locale === "zh" ? "zh-CN" : "en-US", {
    month: "short",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

